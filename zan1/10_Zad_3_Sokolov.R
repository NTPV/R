# «Правило повтора векторов». При сложении,делении, вычитании, 
# умножении, сравнении векторов разной длины:
# более короткий вектор повторяется с начала.
# Если длины векторов не будут кратны, то об этом будет предупреждение.
#Правило повтора векторов (Recycling Rule)
x<-c(2,4,5,3,-4,0)
x         # 2  4  5  3 -4  0
x*5       # 10  20  25  15 -20   0
y<-c(5,3)
y         # 5 3
x*y # (2  4  5  3 -4  0)*(5 3) = 10  12  25   9 -20   0
z<-c(1,2,3,4)
