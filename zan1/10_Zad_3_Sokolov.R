# Переменной x присвоены значения
x=c(0,1,2,7,10,14,3,89)
# Просмотр заданных значений вектора x
x
# Выбор 6-го значения в векторе x
x[6]
# Выбор 3-8-го значений в векторе x
x[3:8] # 2 7 10 14 3 89
# Выбор 4-го и 7-го значений в векторе x
x[c(4,7)] # 7 3
# Выбор значений вектора x без 3-ей точки
x[-3] # 0  1  7 10 14  3 89
# Выбор значений вектора x без 2го - 5го  значений
x[-(2:5)] #0 14  3 89
# Выбор значений вектора x больше 3
x[x>3]
# Выбор значений вектора x, удовлетворяющие условию: x больше 3 и меньше 70
x[x>3 & x<70]

